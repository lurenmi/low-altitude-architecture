    需求类别 = $Demand
    发包采购单位 = $Buyer
    预算或金额 = $Amount
    线索时间 = $Date
    来源链接 = $Source
    备注 = $Note
  }
}

function Has-MainCase($rows, $project, $source) {
  return @($rows | Where-Object {
      $_.项目名称 -eq $project
    }).Count -gt 0
}

