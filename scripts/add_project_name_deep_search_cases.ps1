function New-MainCase {
  param(
    [string]$Province,
    [string]$City,
    [string]$Project,
    [string]$Type,
    [string]$Buyer,
    [string]$AmountText,
    [string]$AmountWan,
    [string]$Contractor,
    [string]$Date,
    [string]$Year,
    [string]$SourceLevel,
    [string]$Completeness,
    [string]$Source,
    [string]$Evidence,
    [string]$Note
  )

  $row = [ordered]@{
    项目ID = ''
    省份 = $Province
    省内城市区域 = $City
    项目名称 = $Project
    项目类型 = $Type
    项目阶段 = '中标/成交结果'
    是否直接侦测反制相关 = '是'
    发包采购单位 = $Buyer
    项目金额 = $AmountText
    金额万元 = $AmountWan
    承建中标单位 = $Contractor
    中标公告时间 = $Date
    年份 = $Year
    来源等级 = $SourceLevel
    字段完整度 = $Completeness
    来源链接 = $Source
    证据摘要 = $Evidence
    核验备注 = $Note
  }
  foreach ($col in $deviceCols) { $row[$col] = '' }
  [pscustomobject]$row
}

